    ///   대본(ChapterScript)은 VN 재생용으로 지문이 짧고 연출 메모가 섞여 있어 그대로 읽으면 콘티처럼 읽힌다.
    ///   리더(StoryReaderUI)는 여기서 ① 지난 이야기(Recap) ② 장면 캡션(Caption: 장소·시간) ③ 지문을 소설 문장으로(Prose)
    ///   ④ 제주말 풀이(Gloss)를 가져다 붙인다. 대사는 손대지 않고, VN 재생은 원문 그대로다.
    ///   Prose 의 키는 대본 지문 원문과 **정확히** 같아야 한다(다르면 원문 그대로 표시).
    public static class StoryProse
    {
        public static string Recap(int chapter) => _recap.TryGetValue(chapter, out var s) ? s : null;
        public static string Caption(string sceneId, int bgIndex) => _caption.TryGetValue(sceneId + "#" + bgIndex, out var s) ? s : null;
        public static string Prose(string original)
        {
            if (string.IsNullOrEmpty(original)) return original;
            return _prose.TryGetValue(original.Trim(), out var s) ? s : original;
        }
        /// 대사 안에 나온 제주말만 골라 「말 — 뜻」 줄로.
        public static string Glossary(IEnumerable<string> dialogueLines)
        {
            var seen = new List<string>();
            foreach (var d in dialogueLines)
            {
                if (string.IsNullOrEmpty(d)) continue;
                foreach (var g in _gloss) if (!seen.Contains(g.Key) && d.Contains(g.Key)) seen.Add(g.Key);
            }
            if (seen.Count == 0) return null;
            var sb = new StringBuilder();
            foreach (var w in seen) { if (sb.Length > 0) sb.Append('\n'); sb.Append(w).Append("  —  ").Append(_gloss[w]); }
            return sb.ToString();
        }

